/** 작은 SVG placeholder (data URL) — UI용 대표/후기 이미지 */
function placeholderImage(label: string, color: string) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="640" height="400" viewBox="0 0 640 400"><rect fill="${color}" width="640" height="400"/><text x="50%" y="50%" fill="#fff" font-size="28" font-family="sans-serif" text-anchor="middle" dominant-baseline="middle">${label}</text></svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

function placeMeta(
  name: string,
  lat: number,
  lng: number,
): Pick<Place, "naverPlaceId"> {
  const mapx = Math.round(lng * 10_000_000);
  const mapy = Math.round(lat * 10_000_000);
  return {
    naverPlaceId: `${mapx}-${mapy}-${name}`,
  };
}

